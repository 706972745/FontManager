import { create } from "zustand";

/**
 * 侧栏停靠面板「当前指针停在哪个面板」—— 全局单值。
 *
 * 为什么各个面板不能自己 `:hover`：
 * 分组面板与标签面板是**上下相邻**的两个面板。鼠标从标签内容区移向分组头部时，
 * 必然先离开标签 → 标签开始收起（释放两百多像素），下方面板整体被往下推，
 * 指针当场脱靶，于是分组**还没展开就被甩开**（用户 2026-11-16 原话：
 * 「先移动到标签展开后，再移动到分组，会直接收起来，而不展开分组」）。
 *
 * 改成全局单值之后：指针一进入某个面板就立刻把 active 切过去，另一个面板
 * **同一帧**开始收起，与这个的展开动画并行 —— 净位移只剩
 * 「展开高度 − 收起高度」，指针仍落在面板内，不会脱靶。
 *
 * 离开时由面板自己延迟 200ms 再清（给「从面板移到相邻面板」留出路）。
 */
export const useDockHover = create<{
  active: string | null;
  setActive: (id: string | null) => void;
}>((set) => ({
  active: null,
  setActive: (active) => set({ active }),
}));

/** 离开后的收起延迟（ms）。太短会脱靶，太长会有「鼠标走了它还赖着」的粘滞感 */
export const DOCK_LEAVE_DELAY = 200;
