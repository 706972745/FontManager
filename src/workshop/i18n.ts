const DICTS: Record<PanelLocale, Dict> = {
  en, de, es, fr, ja, "pt-BR": ptBR, ru, "zh-CN": zhCN, "zh-TW": zhTW,
};

/** 语言码是否认识（主程序下发的语言码都是这 9 个之一） */
export function isPanelLocale(v: string | null): v is PanelLocale {
  return v !== null && (PANEL_LOCALES as readonly string[]).includes(v);
}

/**
 * 查词条。`count` 走复数规则（和主包同一套：按语言的复数类别取
 * `key_one` / `key_few` / `key_many` / `key_other`）。
 */
export function panelT(
  locale: PanelLocale,
  key: string,
  vars?: Record<string, string | number>,
): string {
  const dict = DICTS[locale] ?? en;
  let text = dict[key];
  if (text === undefined) {
    // 复数：先按语言规则挑类别，再回落到 _other，最后回落英文
    const plural = pluralCategory(locale, vars?.count);
    text = dict[`${key}_${plural}`] ?? dict[`${key}_other`] ?? en[`${key}_${plural}`] ?? en[`${key}_other`];
  }
  if (text === undefined) return key;
  if (!vars) return text;
  return text.replace(/\{(\w+)\}/g, (whole, name: string) =>
    name in vars ? String(vars[name]) : whole,
  );
}

/** 该语言对 `count` 用哪个复数类别（Intl.PluralRules 的 select） */
export function pluralCategory(locale: PanelLocale, count?: number | string): string {
  const n = typeof count === "number" ? count : Number(count ?? 0);
  try {
    return new Intl.PluralRules(locale).select(Number.isFinite(n) ? n : 0);
  } catch {
    return "other";
  }
}
